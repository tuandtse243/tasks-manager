# Scenario: Existing workflow
test_init_keeps_projects_own_deploy_workflow() {
  deploy_env "$STANDARD
deploy:
  platform: docker"
  mkdir -p "$SCRUM_REPO_DIR/.github/workflows"
  printf 'name: our deploy\n' > "$(wf)"
  run_scrum init --force
  assert_status 0 "$STATUS" "$ERR"
  assert_eq "name: our deploy" "$(cat "$(wf)")"
  assert_contains "$OUT" "skipped       .github/workflows/deploy.yml (the project's own deployment workflow; left unchanged)"
  assert_eq "" "$(jq -r '.files[".github/workflows/deploy.yml"] // ""' "$SCRUM_REPO_DIR/.github/scrum/files.json")"
  # Uninstall leaves it too.
  run_scrum uninstall --yes
  assert_eq "name: our deploy" "$(cat "$(wf)")"
}

test_init_updates_its_own_deploy_workflow_and_uninstall_removes_it() {
  deploy_env "$STANDARD
deploy:
  platform: docker"
  run_scrum init
  assert_contains "$(cat "$(wf)")" "docker compose"
  printf '%s\n' "$STANDARD
deploy:
  platform: cloudflare" > "$SCRUM_REPO_DIR/.github/scrum.yml"
  run_scrum init
  assert_status 0 "$STATUS" "$ERR"
  assert_contains "$OUT" "updated       .github/workflows/deploy.yml"
  assert_contains "$(cat "$(wf)")" "wrangler"
  run_scrum uninstall --yes
  assert_status 0 "$STATUS" "$ERR"
  [ ! -e "$(wf)" ] || _fail "uninstall left the generated deploy.yml"
}


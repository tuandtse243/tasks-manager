# spec: deploy-templates (delta of branching-and-release-flow)

deploy_env() { # deploy_env YAML
  setup_fake_gh
  setup_repo "$1"
  route 'api --paginate repos/acme/blog/labels*' "labels.json"
  cp "$FIXTURES/labels-github-default.json" "$FAKE_GH_DIR/labels.json"
}
wf() { printf '%s' "$SCRUM_REPO_DIR/.github/workflows/deploy.yml"; }
rendered() { # rendered PLATFORM  Installs the template with preset standard; prints its path.
  deploy_env "$STANDARD
deploy:
  platform: $1" >/dev/null
  run_scrum init
  [ "$STATUS" = 0 ] || _fail "init failed: $ERR"
  wf
}
STANDARD='branching:
  preset: standard
statuses:
  in_review: In review'
ENVIRONMENTS='branching:
  preset: environments
statuses:
  in_review: In review'
TRUNK='branching:
  preset: trunk'

# ---------- Branches map to environments ----------

assert_mapping() { # assert_mapping PRESET_YAML PLATFORM MAP_JSON BRANCHES_JSON OPTIONS_JSON
  deploy_env "$1
deploy:
  platform: $2"
  run_scrum init
  assert_status 0 "$STATUS" "$ERR"
  [ -f "$(wf)" ] || _fail "deploy.yml not installed for $2"
  assert_eq "" "$(grep -E "\{\{[A-Z_]+\}\}" "$(wf)" || true)" "unfilled placeholder"
  assert_json_eq "$3" "$(yq '.jobs.plan.steps[0].env.BRANCH_ENVIRONMENTS' "$(wf)")"
  assert_json_eq "$4" "$(yq -o=json '.on.push.branches' "$(wf)" | jq -c .)"
  assert_json_eq "$5" "$(yq -o=json '.on.workflow_dispatch.inputs.environment.options' "$(wf)" | jq -c .)"
  assert_contains "$OUT" "created       .github/workflows/deploy.yml"
}

# Scenario: Standard
test_deploy_standard_maps_develop_to_staging() {
  assert_mapping "$STANDARD" docker '{"develop":"staging","main":"production"}' '["develop","main"]' '["staging","production"]'
}

# Scenario: Environments
test_deploy_environments_maps_staging_to_staging() {
  assert_mapping "$ENVIRONMENTS" docker '{"develop":"development","staging":"staging","main":"production"}' \
    '["develop","staging","main"]' '["development","staging","production"]'
}

test_deploy_trunk_maps_main_to_production() {
  assert_mapping "$TRUNK" cloudflare '{"main":"production"}' '["main"]' '["production"]'
}

test_deploy_renamed_branches() {
  assert_mapping "branching:
  preset: standard
  develop: dev
  main: trunk
statuses:
  in_review: In review" cloudflare '{"dev":"staging","trunk":"production"}' '["dev","trunk"]' '["staging","production"]'
}

# ---------- Docker deployment builds once; Production needs approval; Rollback ----------

test_deploy_docker_workflow() {
  local f c
  f="$(rendered docker)"
  c="$(cat "$f")"
  assert_eq "# Generated by scrum-github." "$(head -1 "$f" | cut -c1-28)"
  assert_contains "$c" "git rev-parse 'HEAD^{tree}'"
  assert_contains "$c" 'docker manifest inspect "$image:$tree"'
  assert_contains "$c" 'image="ghcr.io/'
  assert_contains "$c" "docker compose pull && IMAGE='\$IMAGE' docker compose up -d"
  assert_contains "$c" "buildx imagetools create"
  assert_eq '${{ needs.plan.outputs.environment }}' "$(yq '.jobs.deploy.environment' "$f")"
  assert_eq "string" "$(yq '.on.workflow_dispatch.inputs.version.type' "$f")"
  assert_eq "choice" "$(yq '.on.workflow_dispatch.inputs.environment.type' "$f")"
  # Scenario: Missing secrets — a step fails with the names of the missing secrets.
  local check; check="$(yq '.jobs.deploy.steps[0].run' "$f")"
  for s in DEPLOY_HOST DEPLOY_USER DEPLOY_SSH_KEY DEPLOY_KNOWN_HOSTS; do
    assert_contains "$check" "missing=\"\$missing $s\""
  done
  assert_contains "$check" "exit 1"
}

test_deploy_cloudflare_workflow() {
  local f run
  f="$(rendered cloudflare)"
  assert_eq "# Generated by scrum-github." "$(head -1 "$f" | cut -c1-28)"
  run="$(yq '.jobs.deploy.steps[] | select(.name == "Deploy with Wrangler") | .run' "$f")"
  assert_contains "$run" 'wrangler@'
  assert_contains "$run" 'deploy --env "$ENVIRONMENT"'
  assert_eq '${{ secrets.CLOUDFLARE_API_TOKEN }}' "$(yq '.jobs.deploy.steps[] | select(.name == "Deploy with Wrangler") | .env.CLOUDFLARE_API_TOKEN' "$f")"
  assert_eq '${{ secrets.CLOUDFLARE_ACCOUNT_ID }}' "$(yq '.jobs.deploy.steps[] | select(.name == "Deploy with Wrangler") | .env.CLOUDFLARE_ACCOUNT_ID' "$f")"
  assert_eq '${{ needs.plan.outputs.environment }}' "$(yq '.jobs.deploy.environment' "$f")"
  # Rollback: a manual run checks out the tag.
  assert_contains "$(yq '.jobs.plan.steps[0].run' "$f")" 'ref="refs/tags/$INPUT_VERSION"'
  assert_eq '${{ needs.plan.outputs.ref }}' "$(yq '.jobs.deploy.steps[0].with.ref' "$f")"
}

# Scenario: Back to the previous version (both templates take environment and version).
test_deploy_rollback_inputs() {
  local f p
  for p in docker cloudflare; do
    f="$(rendered "$p")"
    assert_eq "true" "$(yq '.on.workflow_dispatch.inputs.version.required' "$f")" "$f"
    assert_eq "true" "$(yq '.on.workflow_dispatch.inputs.environment.required' "$f")" "$f"
    assert_contains "$(yq '.jobs.plan.steps[0].run' "$f")" 'environment="$INPUT_ENVIRONMENT"'
  done
}

# ---------- Secrets are named, never written ----------

test_deploy_templates_name_secrets_only() {
  local f other
  for f in "$PLUGIN_DIR"/templates/deploy/*/deploy.yml; do
    # Every secret is read as ${{ secrets.NAME }}; nothing else is assigned to a secret-like key.
    other="$(grep -nE '(TOKEN|KEY|HOST|USER|ACCOUNT_ID|PASSWORD)[A-Z_]*:[[:space:]]*[^[:space:]]' "$f" \
      | grep -vE ':[[:space:]]*\$\{\{ (secrets\.[A-Z_]+|github\.token) \}\}[[:space:]]*$' || true)"
    assert_eq "" "$other" "$f assigns a value that is not a secret reference"
  done
}

# Scenario: Docker secrets
test_init_docker_lists_secret_names_and_writes_no_value() {
  deploy_env "$STANDARD
deploy:
  platform: docker"
  run_scrum init
  assert_status 0 "$STATUS" "$ERR"
  assert_contains "$OUT" "https://github.com/acme/blog/settings/environments"
  assert_contains "$OUT" "staging (branch develop): DEPLOY_HOST, DEPLOY_USER, DEPLOY_SSH_KEY, DEPLOY_KNOWN_HOSTS"
  assert_contains "$OUT" "production (branch main): DEPLOY_HOST, DEPLOY_USER, DEPLOY_SSH_KEY, DEPLOY_KNOWN_HOSTS"
  assert_contains "$OUT" "required reviewers to the environment production"
  # No secret is read, set or stored: no call to the secrets or environments API.
  assert_not_contains "$(gh_calls)" "secrets"
  assert_not_contains "$(gh_calls)" "environments"
  assert_eq "" "$(grep -rl 'DEPLOY_SSH_KEY=' "$SCRUM_REPO_DIR" || true)" "a value written somewhere"
}

